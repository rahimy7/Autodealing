import { serial, text, integer, boolean, timestamp, uniqueIndex } from "drizzle-orm/pg-core";
import { pgTable, pgEnum } from "./pg-schema";
import { createInsertSchema } from "drizzle-zod";
import { z } from "zod/v4";

// Direction is the same in/out concept as messages, but we keep a separate enum
// because comment "authors" have a different taxonomy (public commenter vs page).
export const feedCommentDirectionEnum = pgEnum("feed_comment_direction", ["in", "out"]);
// Delivery channel INSIDE the comment thread. A comment reply can be published
// as a public reply under the same post, or as a Private Reply that opens a DM.
export const feedCommentDeliveryEnum = pgEnum("feed_comment_delivery", [
  "public_reply",
  "private_reply",
  // Drafts have no delivery yet — set on publish.
  "none",
]);

export const feedCommentsTable = pgTable(
  "feed_comments",
  {
    id: serial("id").primaryKey(),
    threadId: integer("thread_id").notNull(),
    // Meta's comment id — unique per channel. Null for outbound drafts that
    // haven't been published yet.
    externalCommentId: text("external_comment_id"),
    // The parent comment id in Meta, when this is a reply to a specific comment
    // inside the thread. Null for the root comment.
    parentExternalCommentId: text("parent_external_comment_id"),
    direction: feedCommentDirectionEnum("direction").notNull(),
    delivery: feedCommentDeliveryEnum("delivery").notNull().default("none"),
    // Author information. For inbound: from the customer (name captured on the
    // webhook). For outbound: recorded so the panel can show "Ana (virtual)".
    authorName: text("author_name"),
    // FK to agents.id when the reply was drafted/sent by an agent (virtual or human).
    authorAgentId: integer("author_agent_id"),
    content: text("content").notNull(),
    // Drafts wait for human approval and are not delivered to Meta until published.
    isDraft: boolean("is_draft").notNull().default(false),
    // Was generated by the virtual agent (either auto-sent or as a draft).
    isAiSuggestion: boolean("is_ai_suggestion").notNull().default(false),
    // Panel-only note (routing, migration, resolution) — never sent to Meta.
    isInternal: boolean("is_internal").notNull().default(false),
    publishedAt: timestamp("published_at"),
    createdAt: timestamp("created_at").notNull().defaultNow(),
  },
  (t) => ({
    externalCommentUnique: uniqueIndex("feed_comments_external_unique").on(t.externalCommentId),
  }),
);

export const insertFeedCommentSchema = createInsertSchema(feedCommentsTable).omit({
  id: true,
  createdAt: true,
});
export type InsertFeedComment = z.infer<typeof insertFeedCommentSchema>;
export type FeedComment = typeof feedCommentsTable.$inferSelect;
